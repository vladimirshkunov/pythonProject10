"""
Напишите программу, которая вводит символьную строку и определяет количество
пар одинаковых символов, стоящих рядом.
Пример 1:
Введите строку: ABCABCA
Ответ: 0
Пример 2:
Введите строку: ABBCAABCC
Ответ: 3
Пример 3:
Введите строку: AAAAAA
Ответ: 5
"""
s = input()
cnt = 0
for i in range(len(s) - 1):
    if s[i] == s[i + 1]: cnt += 1
print(cnt)
