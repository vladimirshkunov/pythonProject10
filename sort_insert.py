arr = [...]
for i in range(1, len(arr)):
    key = arr[i]  # Текущий элемент, который будем вставлять
    j = i - 1  # Индекс предыдущего элемента в отсортированной части

    # Сдвигаем элементы отсортированной части, которые больше key,
    # на одну позицию вправо
    while j >= 0 and arr[j] > key:
        arr[j + 1] = arr[j]
        j -= 1

    # Вставляем key на освободившееся место
    arr[j + 1] = key
